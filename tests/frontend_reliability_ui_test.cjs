/* Regression coverage for frontend HTTP parsing, latest-only reads and non-aborted saves. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const pathJs = path.join(__dirname, '../src/ffado_webmixer/assets/static');
const source = fs.readFileSync(path.join(pathJs, 'frontend-api.js'), 'utf8');
const pending = [];
const ok = body => ({ok: true, status: 200, json: async () => body});
let fetches = [];
function deferred() { let resolve, reject; const promise = new Promise((a,b) => {resolve=a; reject=b;}); return {promise,resolve,reject}; }
const window = {};
const context = vm.createContext({window, AbortController, Promise, Map, fetch(url, init) {
  fetches.push({url, init});
  if (url === '/bad') return Promise.resolve({ok: false,status:400,json:async()=>({error:'Invalid preference'})});
  if (url === '/server') return Promise.resolve({ok:false,status:503,json:async()=>({})});
  if (url === '/malformed') return Promise.resolve({ok:true,status:200,json:async()=>{throw Error('HTML page');}});
  if (url === '/logical') return Promise.resolve(ok({ok:false,error:'Not saved'}));
  const d=deferred(); pending.push({...d,url,init});
  if (url === '/read') init.signal?.addEventListener('abort', ()=> {
    const e = Error('Cancelled');e.name='AbortError';d.reject(e);
  }, {once:true});
  return d.promise;
}});
vm.runInContext(source, context);
const api = window.ffadoApi;
const settle = async()=>{for(let i=0;i<12;i++) await Promise.resolve();};
(async()=>{
  await assert.rejects(api.request('/bad'), /Invalid preference/);
  await assert.rejects(api.request('/server'), /HTTP 503/);
  await assert.rejects(api.request('/malformed'), /invalid JSON/);
  await assert.rejects(api.request('/logical'), /Not saved/);
  const first=api.latest('mixer','/read',{device:'GUID-A'});
  const firstReq=pending.at(-1);
  const second=api.latest('mixer','/read',{device:'GUID-B'});
  const secondReq=pending.at(-1);
  assert.equal(firstReq.init.signal.aborted,true,'obsolete read is aborted');
  assert.equal(firstReq.init.headers['X-FFADO-Device'],'GUID-A');
  assert.equal(secondReq.init.headers['X-FFADO-Device'],'GUID-B');
  secondReq.resolve(ok({mix:2}));
  assert.deepEqual(await second,{mix:2});
  assert.equal(await first,null,'aborted request does not update the page');
  const third=api.latest('other','/ignored-abort');
  const stale=pending.at(-1);
  const fourth=api.latest('other','/ignored-abort');
  const newest=pending.at(-1);
  stale.resolve(ok({mix:3}));newest.resolve(ok({mix:4}));
  assert.equal(await third,null,'stale response dropped even when network ignores abort');
  assert.deepEqual(await fourth,{mix:4});
  const one=api.serial('settings',()=>api.request('/save',{body:{theme:'dark'},device:'GUID',clientId:'tab'}));
  const posted=pending.at(-1);
  assert.equal(posted.url,'/ignored-abort','serialization begins on next microtask');
  await settle();
  const initialSave=pending.at(-1);
  assert.equal(initialSave.url,'/save');
  assert.equal(initialSave.init.headers['X-Client-Id'],'tab');
  assert.deepEqual(JSON.parse(initialSave.init.body),{theme:'dark'});
  const two=api.serial('settings',()=>api.request('/save',{body:{theme:'light'}}));
  await settle();
  assert.equal(pending.filter(p=>p.url==='/save').length,1,'second write must not overtake first');
  initialSave.resolve(ok({ok:true}));
  assert.deepEqual(await one,{ok:true});
  await settle();
  const lastSave=pending.at(-1);
  assert.equal(lastSave.url,'/save');
  assert.notEqual(lastSave,initialSave);
  lastSave.resolve(ok({ok:true}));
  await two;
  assert.equal(api.isAbort({name:'AbortError'}),true);
  console.log('Frontend API: HTTP errors, JSON errors, GUID guards, stale cancellation, ordered persistence passed');
})().catch(err=>{console.error(err);process.exitCode=1;});
